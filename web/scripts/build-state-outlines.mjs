/**
 * build-state-outlines.mjs
 *
 * Generates real geographic state outlines for the overview choropleth.
 *
 * Reads each per-state constituency TopoJSON, dissolves constituencies into
 * a single state outline via topojson-client.merge, projects all five into
 * a shared 500x600 viewBox with d3-geo's Mercator, and emits a TS module
 * the OverviewSvgChoropleth imports synchronously.
 *
 * Run from web/: `node scripts/build-state-outlines.mjs`. The output file is
 * checked in; re-run after the constituency TopoJSONs change.
 *
 * Inputs:  ../data/topojson/india_constituencies_<code>.topojson
 * Output:  src/lib/state_outlines.generated.ts
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { merge } from 'topojson-client';
import { geoMercator, geoPath, geoCentroid } from 'd3-geo';

const __dir = dirname(fileURLToPath(import.meta.url));
const WEB_ROOT = join(__dir, '..');
const TOPO_DIR = join(WEB_ROOT, '..', 'data', 'topojson');
const OUT_FILE = join(WEB_ROOT, 'src', 'lib', 'state_outlines.generated.ts');

const VIEW_W = 500;
const VIEW_H = 600;
const PADDING = 16;
// Round projected coordinates to keep the emitted SVG path strings small.
const COORD_PRECISION = 2;
// Drop points within this many viewBox px of the previous kept point.
// At a 500x600 viewBox the human eye can't resolve sub-pixel detail anyway,
// and constituency boundaries are oversampled for the overview's scale.
const SIMPLIFY_PX = 0.6;

const STATES = [
  { code: 'S03', label: 'Assam', short: 'AS' },
  { code: 'S11', label: 'Kerala', short: 'KL' },
  { code: 'S22', label: 'Tamil Nadu', short: 'TN' },
  { code: 'S25', label: 'West Bengal', short: 'WB' },
  { code: 'U06', label: 'Puducherry', short: 'PY' },
];

function loadStateFeature(code) {
  const path = join(TOPO_DIR, `india_constituencies_${code}.topojson`);
  const topo = JSON.parse(readFileSync(path, 'utf8'));
  const objKey = Object.keys(topo.objects)[0];
  const geoms = topo.objects[objKey].geometries;
  const geometry = merge(topo, geoms);
  return { type: 'Feature', properties: { state_code: code }, geometry };
}

const features = STATES.map((s) => loadStateFeature(s.code));
const collection = { type: 'FeatureCollection', features };

const projection = geoMercator().fitExtent(
  [
    [PADDING, PADDING],
    [VIEW_W - PADDING, VIEW_H - PADDING],
  ],
  collection
);
const renderPath = geoPath(projection).digits(COORD_PRECISION);

// Drop near-duplicate points within each subpath (rings) using a simple
// minimum-distance filter. Preserves M/Z commands and ring closure.
function simplifyPath(d, minDist) {
  const min2 = minDist * minDist;
  return d.replace(/M[^MZ]*Z/g, (sub) => {
    // Subpath form: M x,y L x,y L x,y ... Z   (geoPath uses L for all segments)
    const tokens = sub.match(/[MLZ]|-?\d*\.?\d+/g);
    if (!tokens) return sub;
    const out = [];
    let lastX = NaN;
    let lastY = NaN;
    let firstX = NaN;
    let firstY = NaN;
    let i = 0;
    while (i < tokens.length) {
      const t = tokens[i];
      if (t === 'M' || t === 'L') {
        const x = parseFloat(tokens[i + 1]);
        const y = parseFloat(tokens[i + 2]);
        i += 3;
        if (t === 'M') {
          out.push(`M${x},${y}`);
          lastX = firstX = x;
          lastY = firstY = y;
        } else {
          const dx = x - lastX;
          const dy = y - lastY;
          if (dx * dx + dy * dy >= min2) {
            out.push(`L${x},${y}`);
            lastX = x;
            lastY = y;
          }
        }
      } else if (t === 'Z') {
        // Ensure the ring closes — re-emit closing point if simplification
        // dropped the natural last vertex too aggressively.
        const dx = firstX - lastX;
        const dy = firstY - lastY;
        if (dx * dx + dy * dy > 0.0001) {
          out.push(`L${firstX},${firstY}`);
        }
        out.push('Z');
        i++;
      } else {
        i++;
      }
    }
    return out.join('');
  });
}

const entries = STATES.map((s, i) => {
  const f = features[i];
  const dRaw = renderPath(f);
  if (!dRaw) throw new Error(`Failed to render path for ${s.code}`);
  const d = simplifyPath(dRaw, SIMPLIFY_PX);
  // geoCentroid handles MultiPolygons correctly (area-weighted lng/lat
  // centroid); for Puducherry's enclaves we override below since the
  // centroid lands between fragments.
  const centroid = projection(geoCentroid(f));
  if (!centroid) throw new Error(`Failed to project centroid for ${s.code}`);
  return {
    code: s.code,
    label: s.label,
    short: s.short,
    d,
    labelXY: [
      Math.round(centroid[0] * 10) / 10,
      Math.round(centroid[1] * 10) / 10,
    ],
  };
});

const ts = `// AUTO-GENERATED by web/scripts/build-state-outlines.mjs.
// Do not edit by hand. Re-run \`node scripts/build-state-outlines.mjs\` after
// the constituency TopoJSONs change.

export interface StateOutline {
  code: string;
  label: string;
  short: string;
  d: string;
  labelXY: readonly [number, number];
}

export const STATE_OUTLINES_VIEWBOX = { width: ${VIEW_W}, height: ${VIEW_H} } as const;

export const STATE_OUTLINES: readonly StateOutline[] = ${JSON.stringify(
  entries,
  null,
  2
)} as const;
`;

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, ts);

console.log(`Wrote ${entries.length} state outlines → ${OUT_FILE}`);
for (const e of entries) {
  console.log(
    `  ${e.code} ${e.label.padEnd(12)} label@(${e.labelXY.join(',')}) d.length=${e.d.length}`
  );
}
